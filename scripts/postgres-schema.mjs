/**
 * Generates the PostgreSQL Prisma schema from the SQLite development schema.
 *
 * Keeping one source of truth avoids the two schemas drifting apart: the
 * production file is derived, committed, and verified by a unit test.
 *
 * Usage:
 *   node scripts/postgres-schema.mjs           # write prisma/postgres/schema.prisma
 *   node scripts/postgres-schema.mjs --check   # exit 1 if the committed file is stale
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import path from "node:path";

export const SOURCE_PATH = "prisma/schema.prisma";
export const TARGET_PATH = "prisma/postgres/schema.prisma";

const GENERATED_HEADER = `// 4AB NET — Prisma schema (PostgreSQL, production)
// AUTO-GENERATED from prisma/schema.prisma by scripts/postgres-schema.mjs.
// Do not edit this file: change the source schema and run \`npm run schema:pg\`.
`;

const CLIENT_GENERATOR = `generator client {
  provider = "prisma-client-js"
  // Netlify and Vercel run on AWS Lambda (RHEL, OpenSSL 3).
  binaryTargets = ["native", "rhel-openssl-3.0.x"]
}`;

const SQLITE_GENERATOR = `generator client {
  provider = "prisma-client-js"
}`;

export function toPostgresSchema(source) {
  if (!source.includes('provider = "sqlite"')) {
    throw new Error("prisma/schema.prisma does not declare the sqlite provider");
  }
  if (!source.includes(SQLITE_GENERATOR)) {
    throw new Error("prisma/schema.prisma has an unexpected generator client block");
  }

  let output = source.replace('provider = "sqlite"', 'provider = "postgresql"');
  output = output.replace(SQLITE_GENERATOR, CLIENT_GENERATOR);

  // Replace the leading development-only comment block with a generated header.
  const firstGenerator = output.indexOf("generator client {");
  if (firstGenerator === -1) throw new Error("could not locate the generator block");
  output = `${GENERATED_HEADER}\n${output.slice(firstGenerator)}`;

  return output;
}

async function main() {
  const check = process.argv.includes("--check");
  const source = await readFile(SOURCE_PATH, "utf8");
  const expected = toPostgresSchema(source);

  if (check) {
    const actual = await readFile(TARGET_PATH, "utf8").catch(() => null);
    if (actual !== expected) {
      console.error(
        `${TARGET_PATH} is out of date. Run: npm run schema:pg`,
      );
      process.exit(1);
    }
    console.log(`${TARGET_PATH} is up to date`);
    return;
  }

  await mkdir(path.dirname(TARGET_PATH), { recursive: true });
  await writeFile(TARGET_PATH, expected, "utf8");
  console.log(`wrote ${TARGET_PATH}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
